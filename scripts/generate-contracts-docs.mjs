#!/usr/bin/env node
/**
 * scripts/generate-contracts-docs.mjs
 *
 * P12-023: Documentation generated from source (Public API contracts and types).
 *
 * Exit criterion:
 *   "Public API documentation generated from contracts and types, never written twice.
 *    Documentation regenerates from source; drift fails CI."
 *
 * Usage:
 *   node scripts/generate-contracts-docs.mjs --generate    # Generate docs/programme/PUBLIC-API-CONTRACTS.md
 *   node scripts/generate-contracts-docs.mjs --verify      # Ensure generated doc is in sync with source contracts
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WORKSPACE_DIR = resolve(__dirname, "..");
const PARENT_DIR = resolve(WORKSPACE_DIR, "..");
const CONTRACTS_SRC_DIR = resolve(PARENT_DIR, "unierp-contracts/src");
const DOC_OUTPUT_PATH = resolve(WORKSPACE_DIR, "docs/programme/PUBLIC-API-CONTRACTS.md");

export function generateContractsDocumentation() {
  const sections = [];
  sections.push("# PUBLIC-API-CONTRACTS — Generated Public API Documentation");
  sections.push("");
  sections.push("> **AUTOMATICALLY GENERATED FROM `@kannan19302/contracts` (L0) SOURCE.**");
  sections.push("> Do not edit this file by hand. Run `node scripts/generate-contracts-docs.mjs --generate` to update.");
  sections.push("");
  sections.push("## Overview");
  sections.push("Single source of truth for all external and platform contracts across UniERP.");
  sections.push("");

  if (!existsSync(CONTRACTS_SRC_DIR)) {
    throw new Error(`Contracts source directory not found at: ${CONTRACTS_SRC_DIR}`);
  }

  function scanDir(dir, prefix = "") {
    const entries = readdirSync(dir, { withFileTypes: true });
    for (const ent of entries) {
      const fullPath = join(dir, ent.name);
      if (ent.isDirectory()) {
        scanDir(fullPath, `${prefix}${ent.name}/`);
      } else if (ent.name.endsWith(".ts") && !ent.name.endsWith(".spec.ts")) {
        const fileContent = readFileSync(fullPath, "utf8");
        const relPath = `${prefix}${ent.name}`;
        extractContracts(relPath, fileContent);
      }
    }
  }

  function extractContracts(filePath, content) {
    const lines = content.split("\n");
    const exportedItems = [];

    for (const line of lines) {
      const trimmed = line.trim();
      if (trimmed.startsWith("export interface ") || trimmed.startsWith("export type ") || trimmed.startsWith("export enum ") || trimmed.startsWith("export class ") || trimmed.startsWith("export const ")) {
        exportedItems.push(trimmed.replace(/^export\s+/, "").replace(/\{$/, "").trim());
      }
    }

    if (exportedItems.length > 0) {
      sections.push(`### \`${filePath}\``);
      sections.push("");
      for (const item of exportedItems) {
        sections.push(`- \`${item}\``);
      }
      sections.push("");
    }
  }

  scanDir(CONTRACTS_SRC_DIR);
  return sections.join("\n") + "\n";
}

const isGenerate = process.argv.includes("--generate");
const isVerify = process.argv.includes("--verify") || (!isGenerate && Boolean(process.argv[1]));

const generatedContent = generateContractsDocumentation();

if (isGenerate) {
  writeFileSync(DOC_OUTPUT_PATH, generatedContent, "utf8");
  console.log(`OK    Generated public API documentation at docs/programme/PUBLIC-API-CONTRACTS.md`);
  process.exit(0);
}

if (isVerify) {
  if (!existsSync(DOC_OUTPUT_PATH)) {
    console.error(`FAIL  generate-contracts-docs: Documentation file missing at docs/programme/PUBLIC-API-CONTRACTS.md. Run --generate.`);
    process.exit(1);
  }

  const existingContent = readFileSync(DOC_OUTPUT_PATH, "utf8");
  if (existingContent !== generatedContent) {
    console.error(`FAIL  generate-contracts-docs: Documentation drift detected! docs/programme/PUBLIC-API-CONTRACTS.md is out of sync with @kannan19302/contracts source.`);
    console.error(`      Run \`node scripts/generate-contracts-docs.mjs --generate\` to synchronize.`);
    process.exit(1);
  }

  console.log(`OK    Documentation sync verified: docs/programme/PUBLIC-API-CONTRACTS.md matches @kannan19302/contracts source with zero drift.`);
  process.exit(0);
}
