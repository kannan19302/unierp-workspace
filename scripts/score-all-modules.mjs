#!/usr/bin/env node
// E02 (Track E — business apps): "Every module scored, published as one
// comparable table. The first honest statement of where the product
// actually is." Exit: "45/45 modules scored with evidence. The table is
// committed and becomes the source for E05-E28's priorities."
//
// Runs E01's scripts/score-module.mjs against every module directory under
// unierp-api/src/modules and aggregates the 16-row output into one table,
// written to docs/programme/E02-MODULE-BASELINE.md.
//
//   node scripts/score-all-modules.mjs

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const API_MODULES = path.join(root, 'unierp-api', 'src', 'modules');
const SCORE_SCRIPT = path.join(root, 'unierp-workspace', 'scripts', 'score-module.mjs');
const OUT_FILE = path.join(root, 'unierp-workspace', 'docs', 'programme', 'E02-MODULE-BASELINE.md');

const modules = readdirSync(API_MODULES)
  .filter((entry) => statSync(path.join(API_MODULES, entry)).isDirectory())
  .sort();

const DIMENSIONS = [
  'Data model', 'Lifecycle', 'Authorisation', 'Approvals', 'CRUD depth', 'Validation',
  'Events', 'Reporting', 'Documents', 'Integrations', 'Settings', 'UI states',
  'Accessibility', 'Tests', 'Performance', 'Client parity',
];

const rowLineRe = /^\s*(\d+)\.\s+(.+?)\s{2,}\[(\d)\]\s+(.*)$/;

const results = [];
const failures = [];

for (const mod of modules) {
  let stdout;
  try {
    stdout = execFileSync('node', [SCORE_SCRIPT, mod], { cwd: path.dirname(SCORE_SCRIPT), encoding: 'utf-8' });
  } catch (err) {
    failures.push({ module: mod, error: err.message });
    continue;
  }
  const lines = stdout.split('\n');
  const scores = [];
  for (const line of lines) {
    const m = line.match(rowLineRe);
    if (m) scores.push({ n: Number(m[1]), dimension: m[2].trim(), score: Number(m[3]), evidence: m[4].trim() });
  }
  if (scores.length !== 16) {
    failures.push({ module: mod, error: `expected 16 rows, got ${scores.length}` });
    continue;
  }
  const total = scores.reduce((s, r) => s + r.score, 0);
  const nextLevelRequired = [1, 2, 3, 7, 14];
  const isNextLevel = scores.every((r) => (nextLevelRequired.includes(r.n) ? r.score >= 3 : r.score >= 2));
  results.push({ module: mod, scores, total, isNextLevel });
}

if (failures.length > 0) {
  console.error(`FAILED to score ${failures.length}/${modules.length} module(s):`);
  for (const f of failures) console.error(`  ${f.module}: ${f.error}`);
  process.exit(1);
}

results.sort((a, b) => a.total - b.total);

const lines = [];
lines.push('# E02 — Module completeness baseline');
lines.push('');
lines.push(`Generated by \`node scripts/score-all-modules.mjs\`, which runs E01's \`scripts/score-module.mjs\``);
lines.push(`against every module directory under \`unierp-api/src/modules\`. Sorted lowest total first —`);
lines.push('the modules with the most work ahead, not the ones already closest to done.');
lines.push('');
lines.push(`**${results.length} module(s) scored.** The track brief states "45 business modules"; this`);
lines.push(`checkout has ${modules.length} directories under \`unierp-api/src/modules\` (some — \`outbox\`,`);
lines.push('`admin`, `devops`, `ext-gateway`, `extension-registry`, `api-platform` — are platform/plane-2');
lines.push('infrastructure rather than plane-3 business modules by the track\'s own definition, not business');
lines.push('logic gaps). Reported honestly as the real directory count rather than force-fit to 45.');
lines.push('');
lines.push(`"Next level" = score >=2 on every row, >=3 on rows 1 (Data model), 2 (Lifecycle),`);
lines.push('3 (Authorisation), 7 (Events), 14 (Tests) — per 02-EXECUTION-GUIDELINES §5.');
lines.push('');

const header = ['Module', 'Total /48', 'Next level?', ...DIMENSIONS.map((_, i) => `#${i + 1}`)];
lines.push('| ' + header.join(' | ') + ' |');
lines.push('| ' + header.map(() => '---').join(' | ') + ' |');
for (const r of results) {
  const row = [r.module, `${r.total}`, r.isNextLevel ? 'YES' : 'no', ...r.scores.map((s) => s.score)];
  lines.push('| ' + row.join(' | ') + ' |');
}
lines.push('');

lines.push('## Full evidence per module');
lines.push('');
for (const r of results) {
  lines.push(`### ${r.module} — ${r.total}/48${r.isNextLevel ? ' — NEXT LEVEL' : ''}`);
  lines.push('');
  for (const s of r.scores) {
    lines.push(`- **#${s.n} ${s.dimension} [${s.score}]** — ${s.evidence}`);
  }
  lines.push('');
}

const nextLevelCount = results.filter((r) => r.isNextLevel).length;
lines.push('## Summary');
lines.push('');
lines.push(`- ${results.length} modules scored, all with evidence.`);
lines.push(`- ${nextLevelCount}/${results.length} modules are "next level" by the rubric's own threshold.`);
lines.push(`- Lowest-scoring: ${results.slice(0, 5).map((r) => `${r.module} (${r.total})`).join(', ')}.`);
lines.push(`- Highest-scoring: ${results.slice(-5).reverse().map((r) => `${r.module} (${r.total})`).join(', ')}.`);
lines.push('- Row 15 (Performance) is unmeasured for every module (0 across the board) — no module in');
lines.push('  this checkout has a recorded p95 profiling result. This is the single most consistent gap');
lines.push('  in the table and should be read as "no module has been load-tested," not "every module is');
lines.push('  equally slow."');
lines.push('');
lines.push('This table is the input E05-E28 use to prioritise which modules get audited/deepened next —');
lines.push('lowest total first, per this file\'s own sort order.');
lines.push('');

writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');
console.log(`Scored ${results.length}/${modules.length} modules. Written to ${path.relative(root, OUT_FILE)}`);
console.log(`${nextLevelCount}/${results.length} are "next level". Lowest 5: ${results.slice(0, 5).map((r) => `${r.module}(${r.total})`).join(', ')}`);
